def post_json(endpoint: str, data=None):
    body = json.dumps(data).encode("utf-8") if data is not None else b"{}"
    req = urllib.request.Request(
        f"{BACKEND_BASE}/{endpoint}",
        data=body,
        headers={"Content-Type": "application/json", "User-Agent": "PilotLauncher20/1.0"}
    )
    for attempt in range(3):
        try:
            with urllib.request.urlopen(req, timeout=120) as resp:
                return json.loads(resp.read().decode("utf-8"))
        except Exception as e:
            if attempt == 2:
                raise
            time.sleep(1.0)

def main():
    print("[*] Stopping any previous pilot sessions...")
    try:
        post_json("stop")
    except Exception as e:
        print("    (no active sessions to stop)")

    print(f"[*] Step 1: Sending Preflight for all {len(PAIRS_CONFIG)} pairs (concurrent & fast)...")
    t0 = time.time()
    preflight_res = post_json("preflight", PAIRS_CONFIG)
    dt_preflight = time.time() - t0
    preflight_id = preflight_res.get("preflight_id")
    print(f"[+] Preflight completed in {dt_preflight:.2f}s, preflight_id: {preflight_id}")

    valid_sessions = 0
    for sym, sess in preflight_res.get("sessions", {}).items():
        is_valid = sess.get("preflight_valid")
        if is_valid:
            valid_sessions += 1
        print(f"    - {sym:8s} | valid: {is_valid} | strategy: {sess.get('strategy_type')} ({sess.get('timeframe')})")

    print(f"[*] Valid preflights: {valid_sessions}/{len(PAIRS_CONFIG)}")

    print("[*] Step 2: Starting Live Paper Marathon with Shared $1,000 Balance and Dynamic Leverage/Risk...")
    t1 = time.time()
    endpoint = f"start?preflight_id={preflight_id}" if preflight_id else "start"
    start_res = post_json(endpoint, PAIRS_CONFIG)
    dt_start = time.time() - t1
    print(f"[+] Marathon started in {dt_start:.2f}s")
    print(f"[+] Pilot running status: {start_res.get('pilot_running')}")
    print(f"[+] Shared wallet equity: ${start_res.get('aggregate', {}).get('paper', {}).get('equity')}")
    print(f"[+] Active sessions: {len(start_res.get('sessions', {}))}")

if __name__ == "__main__":
    main()
